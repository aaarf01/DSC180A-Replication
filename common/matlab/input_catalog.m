function C = input_catalog()
% The one place that lists every input file: where it goes, where to get it,
% and which panels need it. Used by setup_data, run_all and every figure runner.
C = struct('key', {}, 'file', {}, 'dest', {}, 'panels', {}, 'source', {}, 'note', {});
C(end+1) = entry('theta', 'thetaPrime_MODIS.mat', 'data', '1A, 2A-F, 3A-F, 4A-D', ...
    'https://datadryad.org/dataset/doi:10.5061/dryad.f4qrfj71p', 'Satellite theta'' (Dryad), 111 MB');
C(end+1) = entry('sst', 'SST_v2_25-04.csv', 'data', '4A-D', ...
    'https://zenodo.org/records/15168108', 'Satellite SST (Zenodo data record), 661 MB');
C(end+1) = entry('woa', 'woa23_all_n00_01.nc', 'data', '1A, 2B', ...
    'https://www.ncei.noaa.gov/data/oceans/woa/WOA23/DATA/nitrate/netcdf/all/1.00/woa23_all_n00_01.nc', ...
    'World Ocean Atlas 2023 nitrate, annual, 1 degree');
C(end+1) = entry('oni', 'oni.ascii.txt', 'data', '3A-F', ...
    'https://www.cpc.ncep.noaa.gov/data/indices/oni.ascii.txt', 'Oceanic Nino Index (NOAA CPC, ERSST v5)');
C(end+1) = entry('pdo', 'ersst.v5.pdo.dat', 'data', '3A-F', ...
    'https://www.ncei.noaa.gov/pub/data/cmb/ersst/v5/index/ersst.v5.pdo.dat', 'Pacific Decadal Oscillation (NOAA NCEI, ERSST v5)');
C(end+1) = entry('wod', 'Dataset S1_WOD.csv', 'data', '4D (optional)', ...
    'Not released. Possibly Dataset S1 of Gerace et al. 2025, PNAS, doi:10.1073/pnas.2411835122', ...
    'Nutricline table: columns lat_degN, lon_degE, Zno3_m');
C(end+1) = entry('inpaint', 'inpaint_nans.m', fullfile('deps', 'inpaint_nans'), 'all MATLAB panels', ...
    'https://www.mathworks.com/matlabcentral/fileexchange/4551-inpaint_nans', ...
    'Gap-filling function (MATLAB File Exchange #4551); the whole folder is copied');
end

function e = entry(key, file, dest, panels, source, note)
e = struct('key', key, 'file', file, 'dest', dest, 'panels', panels, 'source', source, 'note', note);
end
